// Regenerates the binary fixtures from the committed SVG pages. Run: node scripts/make-fixtures.mjs
// Outputs: fixtures/lumen-bookcase.pdf, fixtures/lumen-bookcase/page-N.png, fixtures/not-a-manual.pdf,
// fixtures/mock-failure.pdf and fixtures/manifest.json (content hashes the mock provider matches on).
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../fixtures/', import.meta.url));
const attr = (tag, name) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1];
const num = (tag, name, d = 0) => (attr(tag, name) === undefined ? d : Number(attr(tag, name)));
const hex = (c) => (c && c.startsWith('#') ? rgb(...[1, 3, 5].map((i) => parseInt(c.length === 4 ? c[(i + 1) / 2].repeat(2) : c.slice(i, i + 2), 16) / 255)) : undefined);
const decode = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");

async function svgToPage(pdf, svg, fonts) {
  const H = 1100;
  const page = pdf.addPage([800, H]);
  for (const m of svg.matchAll(/<(rect|line|circle|text)\b([^>]*?)(?:\/>|>([^<]*)<\/text>)/g)) {
    const [, kind, tag, body] = m;
    if (kind === 'rect' && attr(tag, 'width') === '800') continue; // page background
    const fill = hex(attr(tag, 'fill'));
    const stroke = hex(attr(tag, 'stroke'));
    const sw = num(tag, 'stroke-width', 1);
    if (kind === 'rect') {
      page.drawRectangle({ x: num(tag, 'x'), y: H - num(tag, 'y') - num(tag, 'height'), width: num(tag, 'width'), height: num(tag, 'height'), color: fill, borderColor: stroke, borderWidth: stroke ? sw : 0 });
    } else if (kind === 'line') {
      page.drawLine({ start: { x: num(tag, 'x1'), y: H - num(tag, 'y1') }, end: { x: num(tag, 'x2'), y: H - num(tag, 'y2') }, color: stroke ?? rgb(0, 0, 0), thickness: sw });
    } else if (kind === 'circle') {
      page.drawCircle({ x: num(tag, 'cx'), y: H - num(tag, 'cy'), size: num(tag, 'r'), color: fill, borderColor: stroke, borderWidth: stroke ? sw : 0 });
    } else {
      const font = Number(attr(tag, 'font-weight')) >= 600 ? fonts.bold : fonts.regular;
      const size = num(tag, 'font-size', 12);
      const text = decode(body ?? '');
      let x = num(tag, 'x');
      if (attr(tag, 'text-anchor') === 'end') x -= font.widthOfTextAtSize(text, size);
      page.drawText(text, { x, y: H - num(tag, 'y'), size, font, color: hex(attr(tag, 'fill')) ?? rgb(0, 0, 0) });
    }
  }
}

async function newPdf() {
  const pdf = await PDFDocument.create({ updateMetadata: false });
  pdf.setCreationDate(new Date(0));
  pdf.setModificationDate(new Date(0));
  const fonts = { regular: await pdf.embedFont(StandardFonts.Helvetica), bold: await pdf.embedFont(StandardFonts.HelveticaBold) };
  return { pdf, fonts };
}

async function textPdf(lines) {
  const { pdf, fonts } = await newPdf();
  const page = pdf.addPage([600, 800]);
  lines.forEach((l, i) => page.drawText(l, { x: 50, y: 740 - i * 28, size: i === 0 ? 24 : 14, font: i === 0 ? fonts.bold : fonts.regular }));
  return Buffer.from(await pdf.save());
}

const sha = (b) => createHash('sha256').update(b).digest('hex');

// Lumen bookcase: PDF and PNG image set from the same six SVG pages.
const { pdf, fonts } = await newPdf();
const pngs = [];
for (let i = 1; i <= 6; i++) {
  const svg = readFileSync(`${root}lumen-bookcase/page-${i}.svg`, 'utf8');
  await svgToPage(pdf, svg, fonts);
  pngs.push(await sharp(Buffer.from(svg), { density: 96 }).png({ compressionLevel: 9 }).toBuffer());
  writeFileSync(`${root}lumen-bookcase/page-${i}.png`, pngs[i - 1]);
}
const lumenPdf = Buffer.from(await pdf.save());
writeFileSync(`${root}lumen-bookcase.pdf`, lumenPdf);

const notManual = await textPdf(['Grocery list', 'Milk', 'Eggs', 'Bread', 'Apples']);
const failure = await textPdf(['MOCK-FAILURE', 'Uploading this file makes the mock analysis fail on purpose.']);
writeFileSync(`${root}not-a-manual.pdf`, notManual);
writeFileSync(`${root}mock-failure.pdf`, failure);

// Image-set hash: sha256 over "images:<n>" and each file's sha256 in order (src/lib/pipeline/hash.ts mirrors this).
const setHash = (files) => sha(Buffer.from(`images:${files.length}:${files.map(sha).join(',')}`));
const manifest = {
  note: 'Generated by scripts/make-fixtures.mjs. The mock provider matches uploads against these content hashes.',
  lumenBookcasePdf: sha(lumenPdf),
  lumenBookcaseImages: setHash(pngs),
  notAManualPdf: sha(notManual),
  mockFailurePdf: sha(failure),
};
writeFileSync(`${root}manifest.json`, JSON.stringify(manifest, null, 2) + '\n');
