/**
 * Clearly labelled synthetic guide for any upload the mock provider does not recognise, so every upload can be
 * walked through end to end. It invents nothing: one low-confidence placeholder step per page, no measurements,
 * parts or tools, each pointing at its real page.
 */
export const DEMO_STEP_TITLE = 'Demo step - mock analysis';

export function buildDemoDraft(pageCount: number): unknown {
  const stepIds = Array.from({ length: pageCount }, (_, i) => `demo-${i + 1}`);
  const steps = Object.fromEntries(
    stepIds.map((id, i) => [
      id,
      {
        id,
        phaseId: 'demo',
        title: DEMO_STEP_TITLE,
        instruction: `This is a placeholder step made by the mock analysis, not a real instruction. Open page ${i + 1} of your document to see what it actually says.`,
        partsUsed: [],
        toolsUsed: [],
        warnings: [],
        irreversible: false,
        confidence: 'low',
        interpretedFromDiagram: false,
        sources: [{ pageIndex: i, regionFallback: true }],
        highlights: [],
      },
    ]),
  );
  return {
    schemaVersion: 1,
    language: 'en',
    title: `Demo guide (mock analysis, ${pageCount} ${pageCount === 1 ? 'page' : 'pages'})`,
    summary: 'This guide was generated by the mock analysis used for development. It only walks through your pages in order; it does not read your manual. Real analysis is not switched on.',
    category: 'demo',
    difficulty: 1,
    peopleNeeded: 1,
    safetyCritical: false,
    tools: [],
    parts: [],
    phases: [{ id: 'demo', title: 'Pages (mock analysis)', stepIds }],
    steps,
    glossary: [],
    unreadablePages: [],
  };
}
